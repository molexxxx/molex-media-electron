/** The verdict a stream ends with; 'refused' means the static plan refused the file before FFmpeg ran. */
export type Verdict = 'verified' | 'verified-below-target' | 'outside-tolerance' | 'passthrough' | 'refused'

/** The scenarios a case feeds. */
export type Scenario = 'G2' | 'G3' | 'G4' | 'G5' | 'G6' | 'G7' | 'G8' | 'G9' | 'G12' | 'G13' | 'G18' | 'G21' | 'G22'

/** A normalize recipe as a preset plus the fields a case sets over it. */
export interface CaseRecipe
{
  preset: PresetId
  /** The output codec; the source's own when omitted. */
  codec?: OutputCodec
  kbpsPerPair?: number | null
  integratedLufs?: number
  maxTruePeakDbtp?: number
  policy?: UnreachablePolicy
  maxLimitingDb?: number
  downmix?: DownmixMode | null
  monoToStereo?: boolean
  shortForm?: 'auto' | 'on' | 'off'
}

/** What one audio stream of a case is expected to end with. */
export interface ExpectedStream
{
  verdict: Verdict
  /** The gain plan's reason, where the scenario names one. */
  reason?: PlanReason
  /** The output layout as ffprobe reports it, where the scenario names one. */
  layout?: string
  /** Builds whose verdict differs, keyed by a prefix of the build id. */
  builds?: Readonly<Record<string, Verdict>>
}

/** One golden case: an input, a recipe, an output container, and the expected verdict of every stream. */
export interface GoldenCase
{
  id: string
  scenarios: readonly Scenario[]
  /** A corpus file name, or a generated fixture from {@link FIXTURES}. */
  input: string
  recipe: CaseRecipe
  /** The output extension; the source's when omitted. */
  container?: string
  expected: readonly ExpectedStream[]
  /** The refusal code a refused case expects. */
  refusal?: RefusalCode
  /** Encoders the case cannot run without. */
  needs?: readonly string[]
}

/** A generated input the corpus does not hold. */
export interface Fixture
{
  name: string
  role: string
  /** ffmpeg arguments after `-v error -y`, ending before the output path; `{corpus:<name>}` stands for a corpus file. */
  args: readonly string[]
}

