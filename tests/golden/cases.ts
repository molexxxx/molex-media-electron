/** The case with this id; throws when there is none. */
export function caseById(id: string): GoldenCase
{
  const found = CASES.find((c) => c.id === id)
  if (!found)
  {
    throw new Error(`No golden case ${id}`)
  }
  return found
}

/** The cases that feed a scenario. */
export function casesFor(scenario: Scenario): GoldenCase[]
{
  return CASES.filter((c) => c.scenarios.includes(scenario))
}

/** The expected verdict of a stream on a build: a matching build override, else the stream's verdict. */
export function expectedVerdict(stream: ExpectedStream, buildId: string): Verdict
{
  const hit = Object.keys(stream.builds ?? {}).find((prefix) => buildId.startsWith(prefix))
  return hit === undefined ? stream.verdict : (stream.builds as Record<string, Verdict>)[hit]
}

/** The whole normalize recipe a case runs: the preset applied with its output policy, then the case's fields. */
export function recipeOf(c: GoldenCase): NormalizeRecipe
{
  const r = c.recipe
  const recipe = applyLoudnessPreset(r.preset, r.codec ? { kind: 'codec', codec: r.codec, kbpsPerPair: r.kbpsPerPair ?? null } : { kind: 'same-as-source' })
  if (r.integratedLufs !== undefined) recipe.target.integratedLufs = r.integratedLufs
  if (r.maxTruePeakDbtp !== undefined) recipe.target.maxTruePeakDbtp = r.maxTruePeakDbtp
  if (r.policy !== undefined) recipe.policy = r.policy
  if (r.maxLimitingDb !== undefined) recipe.maxLimitingDb = r.maxLimitingDb
  if (r.downmix !== undefined) recipe.downmix = r.downmix
  if (r.monoToStereo !== undefined) recipe.monoToStereo = r.monoToStereo
  if (r.shortForm !== undefined && recipe.shortForm) recipe.shortForm = { ...recipe.shortForm, mode: r.shortForm }
  return recipe
}

/** The output extension of a case. */
export function containerOf(c: GoldenCase): string
{
  return (c.container ?? c.input.slice(c.input.lastIndexOf('.') + 1)).toLowerCase()
}

/** One case after its job ran. */
export interface CaseRun
{
  c: GoldenCase
  inputPath: string
  result: AudioJobResult
  events: AudioEvent[]
  /** The argument list of every FFmpeg run the job spawned, in order. */
  runs: string[][]
  /** Every path the job was handed through `deps.output`. */
  outputs: string[]
  warnings: string[]
  ms: number
}

const fixtures = new Map<string, Promise<string>>()

async function makeFixture(golden: GoldenInfo, fixture: Fixture): Promise<string>
{
  const dir = join(golden.dir, 'fixtures')
  const path = join(dir, fixture.name)
  if (existsSync(path))
  {
    return path
  }
  await mkdir(dir, { recursive: true })
  const tmp = join(dir, `tmp-${fixture.name}`)
  const args = fixture.args.map((a) =>
  {
    const named = /^\{corpus:(.+)\}$/.exec(a)
    if (named && !golden.corpus[named[1]]) throw new Error(`Fixture ${fixture.name} needs ${named[1]}, which this build's corpus lacks`)
    return named ? golden.corpus[named[1]] : a
  })
  const run = await runTool(golden.ffmpeg, ['-hide_banner', '-nostdin', '-v', 'error', '-y', ...args, tmp])
  if (run.code !== 0)
  {
    throw new Error(`Fixture ${fixture.name} exited with ${run.code}: ${lf(run.stderr).trim()}`)
  }
  await rename(tmp, path)
  return path
}

/** The path of a corpus file or a generated fixture, generating the fixture once per build. */
export function inputOf(golden: GoldenInfo, name: string): Promise<string>
{
  const corpus = golden.corpus[name]
  if (corpus)
  {
    return Promise.resolve(corpus)
  }
  const fixture = FIXTURES.find((f) => f.name === name)
  if (!fixture)
  {
    return Promise.reject(new Error(`${name} is neither a corpus file nor a fixture`))
  }
  let pending = fixtures.get(name)
  if (!pending)
  {
    pending = makeFixture(golden, fixture)
    fixtures.set(name, pending)
  }
  return pending
}

/** The capabilities the job functions see for a build. */
export function capsOf(golden: GoldenInfo): AudioJobDeps['caps']
{
  return { encoders: new Set(golden.encoders), experimental: new Set(golden.experimental), soxr: golden.soxr }
}

/** Why a case cannot run on a build (a missing input or encoder), or null. */
export function unavailable(c: GoldenCase, golden: GoldenInfo): string | null
{
  if (golden.missing[c.input])
  {
    return `${c.input}: ${golden.missing[c.input]}`
  }
  const lacking = (c.needs ?? []).filter((e) => !golden.encoders.includes(e))
  return lacking.length > 0 ? `the build has no ${lacking.join(', ')}` : null
}

/** Runs a case through `runAudioJob` with a real exec and probe; outputs land in `<outDir>/jobs`. */
export async function runCase(c: GoldenCase, golden: GoldenInfo): Promise<CaseRun>
{
  const inputPath = await inputOf(golden, c.input)
  const dir = join(golden.outDir, 'jobs')
  await mkdir(dir, { recursive: true })
  const container = containerOf(c)
  const muxer = containerFor(container).muxer
  if (muxer === null)
  {
    throw new Error(`${c.id}: no muxer for .${container}`)
  }
  const exec = createExec(golden.ffmpeg, { timers: realTimers })
  const runs: string[][] = []
  const outputs: string[] = []
  const events: AudioEvent[] = []
  const warnings: string[] = []
  const deps: AudioJobDeps = {
    exec:
    {
      run: (args, o) =>
      {
        runs.push([...args])
        return exec.run(args, o)
      }
    },
    probe: createProbe(golden.ffprobe) as AudioJobDeps['probe'],
    caps: capsOf(golden),
    buildId: golden.buildId,
    output: (ext, pass) =>
    {
      const path = join(dir, `${c.id}.${pass}.${ext}.part`)
      outputs.push(path)
      return path
    },
    fs: { remove: (path) => rm(path, { force: true }), size: async (path) => (await stat(path)).size },
    emit: (e) => events.push(e),
    log: (entry) =>
    {
      if (entry.level === 'warn' || entry.level === 'error') warnings.push(`${entry.level}: ${entry.message}`)
    },
    now: () => Date.now()
  }
  for (const name of await readdir(dir))
  {
    if (name.startsWith(`${c.id}.`)) await rm(join(dir, name), { force: true })
  }
  const source = await stat(inputPath)
  const started = Date.now()
  const result = await runAudioJob({
    jobId: c.id,
    sourcePath: inputPath,
    sourceSize: source.size,
    sourceMtimeMs: source.mtimeMs,
    recipe: recipeOf(c),
    facts: null,
    output: { container, muxer }
  }, deps, new AbortController().signal)
  return { c, inputPath, result, events, runs, outputs, warnings, ms: Date.now() - started }
}

/** Runs tasks with at most `limit` in flight, keeping their order. */
export async function pool<T, R>(items: readonly T[], limit: number, task: (item: T) => Promise<R>): Promise<R[]>
{
  const out: R[] = new Array(items.length)
  let next = 0
  const worker = async (): Promise<void> =>
  {
    while (next < items.length)
    {
      const i = next++
      out[i] = await task(items[i])
    }
  }
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, worker))
  return out
}
