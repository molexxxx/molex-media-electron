/** A registry key. The union is closed, so an unknown name fails type checking. */
export type IconName = keyof typeof ICONS

/** Pixel sizes tied to type: sm beside label and caption text, md beside body and control text, lg beside section and title text. */
export const ICON_SIZES = { sm: 14, md: 16, lg: 20 } as const

/** One of the three icon sizes. */
export type IconSize = keyof typeof ICON_SIZES

/** The one line weight in px; with an absolute stroke it holds at every icon size. */
export const ICON_STROKE_WIDTH = 1.5

/** Every registry key, in registry order. */
export const ICON_NAMES = Object.keys(ICONS) as IconName[]
